/** `x\ty\tw\th\tmetin` satırlarını span'a çevirir. */
function ayikla(blok: string): TextSpan[] {
  return blok
    .split("\n")
    .filter((s) => s !== "")
    .map((satir) => {
      const [x, y, w, h, ...metin] = satir.split("\t");
      return {
        text: metin.join("\t"),
        x: Number(x), y: Number(y), w: Number(w), h: Number(h),
      };
    });
}

