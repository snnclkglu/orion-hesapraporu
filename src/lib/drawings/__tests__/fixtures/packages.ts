export interface FixtureFile {
  /** Kök klasör adı atılmış, NFC normalize, '/' ayraçlı yol */
  path: string;
  size: number;
  /** SHA-256'nın ilk 16 hanesi */
  hash: string;
}

export interface FixturePackage {
  folder: string;
  files: FixtureFile[];
}

function ayikla(blok: string): FixtureFile[] {
  return blok
    .trim()
    .split("\n")
    .map((satir) => {
      const [path, size, hash] = satir.split("\t");
      return { path, size: Number(size), hash };
    });
}

