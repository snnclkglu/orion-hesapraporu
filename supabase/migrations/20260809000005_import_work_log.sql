resolved as (
  select
    s.work_date, s.item_no, s.part_code, s.people, s.hours,
    p.id as part_id,
    c.id as category_id,
    ji.id as job_item_id,
    coalesce(ji.job_id, j.id) as job_id
  from src s
  join public.work_parts p on p.name = s.part_name
  join public.work_categories c on c.name = s.category_name
  -- Kalem numaraları veride tekildir; yine de `limit 1` ile bir satıra sabitlenir
  -- (join'in satır çoğaltması aktarımı sessizce ikiye katlardı).
  left join lateral (
    select x.id, x.job_id from public.job_items x where x.item_no = s.item_no limit 1
  ) ji on true
  left join lateral (
    select y.id from public.jobs y where y.job_no = left(s.item_no, 4) limit 1
  ) j on true
)
insert into public.work_logs
  (work_date, item_no, job_id, job_item_id, part_id, category_id, part_code,
   people, hours, created_by)
select
  r.work_date, r.item_no, r.job_id, r.job_item_id, r.part_id, r.category_id,
  r.part_code, r.people, r.hours, a.id
from resolved r cross join actor a
where not exists (
  select 1 from public.work_logs w
  where w.work_date = r.work_date
    and w.item_no = r.item_no
    and w.part_id = r.part_id
    and w.category_id = r.category_id
    and w.people = r.people
    and w.hours = r.hours
);
